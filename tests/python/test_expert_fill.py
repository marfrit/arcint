# How far past the u4 representation's own half-step a measured error may sit
# and still count as "at the representation's floor". This is NOT a fudge
# budget: the codes are chosen against the same f32 scale the graph multiplies
# by, so the bound holds in exact arithmetic, and what is left is the f32
# rounding of the reconstruction itself -- a few ulps on a value of order the
# scale. Measured at real width the worst ratio is 1.000001, i.e. 1e-6 over,
# which is where this number comes from.
_BOUND_SLACK = 1e-5

# The fill's structural acceptance runs at the REAL expert count over two
# layers. Two rather than one because one layer cannot tell a correct fill
# from one that feeds every layer block 0's weights.
_FILL_LAYERS = (0, 1)


