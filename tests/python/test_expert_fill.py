    assert c["experts"] == [E], (
        f"bodies were filled at expert counts {c['experts']}, not the real "
        f"{E} -- the fill is not at real width")

    # the byte count the DECLARED shapes imply, derived here rather than
    # copied from the filler: two [E,I,H/gs,gs] u4 bodies and one
    # [E,H,I/gs,gs], their u4 zero-points, and f32 scales.
    def body_bytes(out, inn):
        groups = inn // gs
        return (E * out * groups * gs // 2          # u4 codes
                + E * out * groups * 1 // 2         # u4 zero-points
                + E * out * groups * 1 * 4)         # f32 scales
    want = len(_FILL_LAYERS) * (2 * body_bytes(I, H) + body_bytes(H, I))
    print(f"  bytes implied by the declared shapes: {want:,}")
    assert c["filled_bytes"] == want, (
        f"the filler produced {c['filled_bytes']:,} B, the declared shapes "
        f"imply {want:,} B")
    assert report["arena_written_bytes"] == want, (
        f"the arena was written {report['arena_written_bytes']:,} B for "
        f"{want:,} B of bodies")

    # ZERO UNWRITTEN BODIES: every u4 expert Constant in the graph must have a
    # placement, and no placement may still be all zeros.
    u4 = [n.get_friendly_name() for n in model.get_ordered_ops()
          if n.get_type_name() == "Constant"
          and n.get_output_element_type(0) == ss.EXPERT_DECLARED_TYPE
          and list(n.get_output_shape(0))[:1] == [E]]
    placed = {p["name"] for p in arena.placements}
    unplaced = sorted(set(u4) - placed)
    assert not unplaced, (
        f"{len(unplaced)} expert-width u4 constants have no arena placement, "
        f"so they were never filled: {unplaced[:6]}")
    # ZERO UNWRITTEN BODIES, read back OUT OF THE PAGES rather than inferred
    # from a byte counter. The fraction of non-zero bytes is the discriminator
    # that works: an unwritten body is 0% non-zero, a body carrying real u4
    # weights is nearly all non-zero, and neither figure depends on the
    # filesystem.
    #
