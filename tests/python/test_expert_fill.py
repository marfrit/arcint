def _expert_piece_model(arena, cfg, E, I, H, M, filler):
    """The tiled expert math over filled bodies, as a standalone model.

    input  x  [E, M, H]
    output y  [E, M, H] = (swish(x @ gate^T) * (x @ up^T)) @ down^T

    This is `emit_moe_tiled`'s expert half -- the three `_compressed_expert`
    chains and the three MatMuls they feed -- lifted out so it can be executed
    without a router, a shared expert or a 248,320-row lm_head.
    """
    x = opv.parameter([E, M, H], ov.Type.f32)
    x.set_friendly_name("x")
    gate = ss._compressed_expert(arena, E, I, H, "piece/experts_gate",
                                 filler, 0, "gate")
    up = ss._compressed_expert(arena, E, I, H, "piece/experts_up",
                               filler, 0, "up")
    down = ss._compressed_expert(arena, E, H, I, "piece/experts_down",
                                 filler, 0, "down")
    g = opv.swish(opv.matmul(x, gate, transpose_a=False, transpose_b=True))
    u = opv.matmul(x, up, transpose_a=False, transpose_b=True)
    y = opv.matmul(opv.multiply(g, u), down,
                   transpose_a=False, transpose_b=True)
    r = opv.result(y)
    r.set_friendly_name("y")
    return ov.Model([r], [x], "filled_expert_piece")


def _numpy_expert_piece(x, gate, up, down):
    """The same arithmetic in f64: swish(x@gate^T) * (x@up^T) then @ down^T."""
    a = np.einsum("emh,eih->emi", x.astype(np.float64), gate.astype(np.float64))
    a = a / (1.0 + np.exp(-a))                       # swish == x * sigmoid(x)
    b = np.einsum("emh,eih->emi", x.astype(np.float64), up.astype(np.float64))
    return np.einsum("emi,ehi->emh", a * b, down.astype(np.float64))


