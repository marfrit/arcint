def test_openvino_u4_element_order_is_the_cpp_contract():
    """THE LOAD-BEARING FACT, and it had never been measured.

    arcint packs u4 "two per byte, even index low nibble"
    (`src/core/gguf_repack.h:90`), executed at `src/core/gguf_repack.cpp:225`:

        q = (r.weights[idx / 2] >> ((idx & 1) * 4)) & 0xF;

    Whether OPENVINO reads a u4 buffer the same way is a separate question,
    and the entire fill rests on the answer: the other convention swaps every
    adjacent pair of weights and yields a model that loads, runs, and is
    wrong -- with no error anywhere.

    Production already bets on it. `src/exec/gguf_graph.cpp:222-223` hands a
    `RepackedTensor::weights` buffer straight to an
    `ov::op::v0::Constant(ov::element::u4, ...)`. This cell is that bet,
    measured.
    """
    buf = np.array([0x21, 0x43], np.uint8)
    t = ov.Tensor(buf, ov.Shape([4]), ov.Type.u4)
    m = ov.Model([opv.result(opv.convert(opv.constant(t), ov.Type.f32))], [],
                 "u4_order")
    out = ov.Core().compile_model(m, "CPU")({})
    got = [int(v) for v in np.asarray(list(out.values())[0]).ravel()]
    cpp = [int(v) for v in ef.unpack_u4(buf, 4)]
    print(f"\n[u4-order] bytes 0x21 0x43 as u4[4]: OpenVINO {got}, "
          f"gguf_repack.cpp:225 {cpp}")
    assert cpp == [1, 2, 3, 4], (
        f"the C++ transcription itself is wrong: {cpp}, expected [1,2,3,4] "
        f"for even-index-low-nibble")
    assert got == cpp, (
        f"OPENVINO AND ARCINT DISAGREE ON u4 NIBBLE ORDER: OpenVINO reads "
        f"{got} where gguf_repack.cpp:225 reads {cpp}. Every adjacent pair of "
        f"expert weights would be swapped. This is not a test to relax -- "
        f"src/exec/gguf_graph.cpp:222 already hands repacked buffers straight "
        f"to an ov u4 Constant in production.")

    # and on a buffer big enough that an accidental agreement is not luck
    rng = np.random.default_rng(20260912)
    q = rng.integers(0, 16, size=4096, dtype=np.uint8)
    packed = ef.pack_u4(q)
    t2 = ov.Tensor(packed, ov.Shape([4096]), ov.Type.u4)
    m2 = ov.Model([opv.result(opv.convert(opv.constant(t2), ov.Type.f32))], [],
                  "u4_order_big")
    back = np.asarray(list(ov.Core().compile_model(m2, "CPU")({}).values())[0])
    back = back.astype(np.uint8).ravel()
    bad = int((back != q).sum())
    print(f"[u4-order] 4096 random codes through pack_u4 -> ov u4 Constant -> "
          f"Convert(f32): {bad} mismatches")
    assert bad == 0, f"{bad} of 4096 codes came back wrong"
    assert np.array_equal(ef.unpack_u4(packed, 4096), q), (
        "the C++ transcription does not invert pack_u4 on random codes")


def test_the_quantiser_holds_its_half_step_bound_and_the_bound_is_tight():
    """The rounding this representation is entitled to, asserted both ways.

    `|v - v_hat| <= scale/2` is the whole tolerance budget the content
    acceptance is allowed to spend, so it must be true (or the acceptance is
    unsound) and it must be nearly attained (or the acceptance is vacuous).

    The awkward case is the one the header explains: the zero-point is an
    integer, so a group whose values are not symmetric about zero has a
    representable interval that misses one end unless the scale is widened
    after the zero-point is rounded. Skipping that step costs a WHOLE step at
    the range ends, not half, so the sweep below deliberately includes
    strongly asymmetric and near-degenerate groups rather than only Gaussian
    ones.
    """
    rng = np.random.default_rng(7)
    gs = 128
    cases = {
        "gaussian": rng.standard_normal((4, 8, 4 * gs)).astype(np.float32),
        "asymmetric +": (rng.random((4, 8, 4 * gs)).astype(np.float32) * 3 + 5),
        "asymmetric -": (-rng.random((4, 8, 4 * gs)).astype(np.float32) * 3 - 5),
        "heavy tail": (rng.standard_normal((4, 8, 4 * gs)).astype(np.float32)
                       ** 5),
        "all zero": np.zeros((2, 3, 2 * gs), np.float32),
        "constant +": np.full((2, 3, 2 * gs), 0.75, np.float32),
        "constant -": np.full((2, 3, 2 * gs), -0.75, np.float32),
    }
    print("\n[u4-quant] case            max|err|      bound      err/bound")
    for name, x in cases.items():
        q, zp, scale = ef.quantise_group_affine(x, gs)
        back = ef.dequantise_affine(q, zp, scale)
        ref = x.reshape(*q.shape)
        err = np.abs(back - ref)
        bound = ef.quantisation_step_bound(scale)
        ratio = err / np.where(bound > 0, bound, 1.0)
        worst = float(ratio.max())
        print(f"[u4-quant] {name:14s} {float(err.max()):.4e}  "
              f"{float(bound.max()):.4e}  {worst:.6f}")
        assert int(q.min()) >= 0 and int(q.max()) <= 15, "codes left [0,15]"
        assert int(zp.min()) >= 0 and int(zp.max()) <= 15, "zp left [0,15]"
        assert worst <= 1.0 + _BOUND_SLACK, (
            f"{name}: an element is {worst:.6f} of a half-step out, past the "
            f"bound the representation guarantees. If the scale is not "
            f"widened after the zero-point is rounded, a value at the end of "
            f"a group's range CLIPS and lands a WHOLE step out.")
        if "constant" in name or "zero" in name:
            assert float(err.max()) == 0.0, (
                f"{name}: a group with one distinct value must be exact, "
                f"got {float(err.max()):.3e}")
    # tightness, on the case where it must be attained
    q, zp, scale = ef.quantise_group_affine(cases["gaussian"], gs)
    ratio = (np.abs(ef.dequantise_affine(q, zp, scale)
                    - cases["gaussian"].reshape(*q.shape))
             / np.where(scale > 0, ef.quantisation_step_bound(scale), 1.0))
    print(f"[u4-quant] tightness on gaussian: max ratio {float(ratio.max()):.4f}, "
          f"mean {float(ratio.mean()):.4f}")
    assert float(ratio.max()) > 0.9, (
        f"the worst error is only {float(ratio.max()):.3f} of the bound; "
        f"either the scale is far larger than the data needs, or the bound "
        f"is not the one this representation actually imposes -- a tolerance "
        f"nothing approaches accepts anything")


def test_the_filler_census_counts_what_it_served_and_catches_a_double_write():
    """The census's own red, synthetic and device-free.

    The structural acceptance below trusts `ExpertFiller.census()`. A census
    that cannot report a double-write would let (a) pass on a build that
    filled one body twice and another never.
    """
    src = lambda layer, kind: np.zeros((2, 4, 128), np.float32)  # noqa: E731
    f = ef.ExpertFiller(src, 128)
    for layer in (0, 1):
        for kind in ("gate", "up", "down"):
            f.body(layer, kind, 2, 4, 128)
    c = f.census()
    print(f"\n[fill-census] clean: {c['bodies']} bodies, layers {c['layers']}, "
          f"kinds {c['kinds']}, double_written {c['double_written']}")
    assert c["bodies"] == 6 and c["layers"] == [0, 1]
    assert c["kinds"] == ["down", "gate", "up"]
    assert c["double_written"] == {}

    f.body(0, "gate", 2, 4, 128)                      # the defect
    c2 = f.census()
    print(f"[fill-census] after a deliberate re-serve: "
          f"double_written {c2['double_written']}")
    assert c2["double_written"] == {(0, "gate"): 2}, c2["double_written"]


