"""CF-COUNTS: a `file:line` citation in tracked prose must resolve to the code
it names.

WHY THIS FILE EXISTS (REVIEW 2a45349 F4, 2026-09-12). This repository's stated
standard is grep-verified citations, and the batch that invented CF-MANIFESTSHA
to stop unenforced claims in the manifest shipped four drifted citations of its
own:

    `gated_delta_state_table.`  cited :3196, the prefix test is at :3195
    `key_cache.`                cited :3200, the prefix test is at :3199
    `value_cache.`              cited :3200, the prefix test is at :3199
    `element_type().size()`     cited  :603, the expression is at  :604

None broke a gate. All four would mislead the next reader, and they drifted for
the ordinary reason: somebody inserted a line above them. A citation written by
hand is correct until the next edit; that is not a property worth having.

The reviewer generalised the class into the PROSE-CLAIM LAW's clause 2 --
"counts are generated by their defining gate at commit time, never recited" --
and a line number is a count.

--------------------------------------------------------------------------
THE TWO LEGS, and what each can and cannot do
--------------------------------------------------------------------------

LEG 1, ANCHORED. The strong one. A row here names the citation AS WRITTEN in
some tracked file, the file it points into, and an ANCHOR -- a substring of the
cited line, which is the thing the author actually meant. The gate resolves the
anchor (asserting it matches exactly one line) and checks the written number
against the resolved one. Both halves can fail usefully: an anchor that matches
nothing means the cited code was deleted or rewritten; an anchor that matches
two lines means the citation identifies nothing; a resolved line number that
disagrees with the prose is the drift above.

This leg is not automatic and cannot be: only a human knows which line a
sentence meant. It covers the citations that carry contract weight -- the OTD
handshake, the paged-port inventory, the slice-bytes constant, the slot
ceiling. `tests/python/test_serving_shape.py` goes further for its own
inventory and does not write the numbers down at all: `_PAGED_PORTS` derives
every one of its thirteen citations from an anchor at import.

LEG 2, RESOLVABILITY. The weak, total one. Every `file:line` in tracked prose
that resolves unambiguously to a file in this repository must point at a line
that EXISTS. This cannot see a one-line drift -- that is exactly what LEG 1 is
for -- but it does catch a citation into a file that has shrunk, or been
renamed, or never existed, and it costs nothing to run over the whole tree.

WHAT IS DELIBERATELY NOT ASSERTED: citations into OTHER repositories.
`docs/research-freetoken.md` cites FreeToken's own `ple.py` at lines 465-478
and four more places -- FreeToken's files (pinned @ 505477ab), not this
repository's `tools/q4e/ple.py`, which is 217 lines long. A basename match
across a repository boundary is a false positive with a confident error
message, the worst kind, so LEG 2 resolves a citation only when the basename
is unique among tracked files AND the citing file is not on the
foreign-citation list below. That list is short and explicit, because "this
citation points somewhere else" should cost a line of prose rather than
silently weakening the gate.

(The first run of LEG 2 failed on THIS DOCSTRING, which had written that
example out as a literal `file:line` and thereby made a claim about
`tools/q4e/ple.py` that its 217 lines cannot satisfy. The scan was right and
the prose was wrong, which is the outcome this file exists to produce.)

Device-free, no shards, no card: it reads text.
"""
import re
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]

_CITE = re.compile(r"\b([A-Za-z0-9_][A-Za-z0-9_./-]*\.(?:cpp|h|py)):(\d+)(?:-(\d+))?")

# Files whose `file:line` citations point into OTHER repositories. A citation
# in one of these is skipped by LEG 2 rather than resolved against a
# same-named file here, which would be a false positive with a confident error
# message -- the worst kind.
_FOREIGN_CITATION_FILES = {
    "docs/research-freetoken.md",       # FreeToken's tree, pinned @ 505477ab
}

# LEG 1. (citing file, the citation exactly as written there, the file it
# points into, an anchor substring of the cited line).
#
# ADD A ROW when a citation starts carrying weight -- when a reader would act
# on it. Do not add rows mechanically; an anchor nobody checked is decoration
# with a test around it.
