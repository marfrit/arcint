def _resolve(cited_path, anchor):
    """The ONE line of `cited_path` containing `anchor`, or a stated failure."""
    p = REPO_ROOT / cited_path
    assert p.is_file(), f"cited file {cited_path} does not exist"
    hits = [i for i, line in enumerate(p.read_text().splitlines(), 1)
            if anchor in line]
    return hits


@pytest.mark.parametrize(
    "citing,written,cited,anchor", _ANCHORED,
    ids=[f"{c.split('/')[-1]}:{w}" for c, w, _, anchor in _ANCHORED])
def test_an_anchored_citation_names_the_line_its_anchor_resolves_to(
        citing, written, cited, anchor):
    """LEG 1. The written number must equal the resolved one."""
    src = (REPO_ROOT / citing)
    assert src.is_file(), f"citing file {citing} does not exist"
    text = src.read_text()
    assert written in text, (
        f"{citing} no longer contains the citation {written!r}. Either it was "
        f"edited (update this row) or removed (delete this row) -- a registry "
        f"row for a citation that is not there gates nothing.")

    hits = _resolve(cited, anchor)
    assert len(hits) == 1, (
        f"{citing} cites {written}; its anchor {anchor!r} matches "
        f"{len(hits)} lines of {cited}"
        + (f" ({hits[:6]})" if hits else " -- the cited code is gone")
        + ". An anchor must identify exactly one line.")
    line = hits[0]
    m = re.fullmatch(r"([A-Za-z0-9_./-]+):(\d+)(?:-(\d+))?", written)
    assert m, f"{written!r} is not a file:line citation"
    start = int(m.group(2))
    end = int(m.group(3)) if m.group(3) else start
    assert start <= line <= end, (
        f"CITATION DRIFT. {citing} writes {written}, but its anchor\n"
        f"    {anchor}\n"
        f"is at {Path(cited).name}:{line}. Correct the prose to "
        f"{Path(cited).name}:{line}"
        + (f" (or widen the range to cover it)" if end != start else "")
        + ". This is REVIEW 2a45349 F4's class: nothing is broken, and the "
          "next reader is sent to the wrong line.")


def test_the_anchored_registry_is_not_empty():
    """A registry of nothing passes every row above vacuously."""
    assert len(_ANCHORED) >= 10, f"only {len(_ANCHORED)} anchored citations"
    citing = {c for c, _, _, _ in _ANCHORED}
    assert len(citing) >= 2, f"only {citing} covered; the registry is too narrow"


def _tracked_files():
    r = subprocess.run(["git", "-C", str(REPO_ROOT), "ls-files"],
                       capture_output=True, text=True, timeout=60)
    assert r.returncode == 0, f"git ls-files failed: {r.stderr[:200]}"
    return r.stdout.split()


def _in_git_worktree():
    try:
        r = subprocess.run(["git", "-C", str(REPO_ROOT), "rev-parse",
                            "--is-inside-work-tree"],
                           capture_output=True, text=True, timeout=10)
        return r.returncode == 0 and r.stdout.strip() == "true"
    except Exception:
        return False


@pytest.mark.skipif(not _in_git_worktree(),
                    reason="not a git work tree (a staged tree has no .git); "
                           "the tracked-file list needs the index")
def test_every_resolvable_citation_points_at_a_line_that_exists():
    """LEG 2, total and weak. Counts are PRINTED, never written down: the
    scanned population is whatever `git ls-files` says today."""
    tracked = _tracked_files()
    by_name = {}
    for t in tracked:
        by_name.setdefault(Path(t).name, []).append(t)

    scanned = resolved = foreign = untracked = ambiguous = 0
    bad = []
    for t in tracked:
        if not t.endswith((".py", ".md", ".cpp", ".h", ".txt")):
            continue
        try:
            src = (REPO_ROOT / t).read_text(errors="replace")
        except OSError:
            continue
        for m in _CITE.finditer(src):
            scanned += 1
            if t in _FOREIGN_CITATION_FILES:
                foreign += 1
                continue
            cands = by_name.get(Path(m.group(1)).name, [])
            if not cands:
                # names a file this repository does not track -- the pinned
                # transformers reference, an OpenVINO header, a plugin source
                untracked += 1
                continue
            if len(cands) > 1:
                ambiguous += 1
                continue
            target = REPO_ROOT / cands[0]
            n = len(target.read_text(errors="replace").splitlines())
            hi = int(m.group(3) or m.group(2))
            resolved += 1
            if hi > n or int(m.group(2)) < 1:
                line = src.count("\n", 0, m.start()) + 1
                bad.append((t, line, m.group(0), cands[0], n))

    print(f"\n[cite-resolve] {scanned} file:line citations in tracked prose")
    print(f"  {resolved:>4} resolved to a tracked file and range-checked")
    print(f"  {untracked:>4} name a file this repo does not track "
          f"(the pin, OpenVINO, plugin sources) -- out of reach, not skipped")
    print(f"  {ambiguous:>4} basename matches several tracked files")
    print(f"  {foreign:>4} in files that cite another repository "
          f"({', '.join(sorted(_FOREIGN_CITATION_FILES))})")
    print(f"  {len(_ANCHORED):>4} ANCHORED: the line NUMBER is checked, not "
          f"merely that the line exists")
    assert resolved + untracked + ambiguous + foreign == scanned
    assert not bad, (
        "citation(s) pointing past the end of the file they name:\n"
        + "\n".join(f"  {t}:{ln}  {cite}  ->  {dest} has {n} lines"
                    for t, ln, cite, dest, n in bad))


def test_the_resolvability_scan_detects_a_line_past_the_end():
    """LEG 2's own red, in tree. The scan's arithmetic, applied to a citation
    that cannot resolve, must reject it -- otherwise the cell above passes for
    files it never really checked."""
    n = len((REPO_ROOT / "tools" / "q4e" / "ple.py").read_text().splitlines())
    for cite, want_bad in ((f"ple.py:{n}", False), (f"ple.py:{n + 1}", True),
                           (f"ple.py:1-{n + 400}", True), ("ple.py:1", False)):
        m = _CITE.fullmatch(cite)
        assert m, cite
        hi = int(m.group(3) or m.group(2))
        assert (hi > n) == want_bad, (
            f"{cite} against a {n}-line file: expected "
            f"{'rejected' if want_bad else 'accepted'}")
    print(f"[cite-resolve] red probe: tools/q4e/ple.py is {n} lines; a "
          f"citation at {n + 1} is rejected, at {n} accepted")
