// FIX D Link 3 (docs/design-qwen-flash-next.md "Links 2 and 3"): the
// (token_history) -> row_index function for Qwen Flash Next's PLE n-gram
// embedding table, plus the dummy-weight derivation of its hash constants.
//
// This is the piece the previous session deferred as a "structural spec hole".
// The hole is closed by the code-side ground truth in docs/research-freetoken.md
// ("Code-side ground truth"), transcribed from the FreeToken reference
// implementation (Apache-2.0, pinned commit 505477ab,
// python/freetoken/models/qwen4_exp/ple.py): the table is NOT "one row per
// token id" -- it is a hashed-vocab lookup addressed by a GLOBAL hashed id.
//
// For each output token and each n-gram order n in [2, ngram_size], the last n
// token ids (with eos substituted wherever the window would cross a sequence
// boundary) are mixed by an XOR of per-position (token * multiplier) products,
// reduced modulo a per-head prime vocab size, and offset into a concatenated
// global row space. `heads_per_ngram` heads share each order's mixed value and
// differ only by their vocab size and offset; there are
// `(ngram_size-1) * heads_per_ngram` heads in total (16 on Qwen3.8: 8 x 2-gram
// + 8 x 3-gram). Each head gathers one 160-wide row, so a token yields
// `num_ngram_heads` rows -> `num_ngram_heads * 160` embedding elements.
//
// The three int64 buffers (layer_multipliers, ngram_heads_vocab_sizes,
// ngram_heads_offsets) ship as trained checkpoint tensors. Until a Flash-Next
// artifact exists, `derive_hash_constants` below reproduces the reference's own
// DUMMY-weight derivation ("the way HF derives them at init",
// ple.py::derive_ngram_hash_constants) -- the same values the reference uses
// as the oracle for a loaded checkpoint. `tests/test_ngram_row_ids.cpp` checks
// both `derive_hash_constants` and `row_ids` byte-for-byte against vectors the
// reference itself produced (tests/ngram_row_ids_vectors.h, generated by
// tools/gen_ngram_vectors.py). A check of arcint's loaded buffers against the
// real checkpoint tensors is still owed once an artifact exists.
//
// Pure integer arithmetic, no torch, no device, no IO -- unit-testable in the
// local (non-OpenVINO) build.

